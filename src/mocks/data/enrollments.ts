// 演示活动 ID (与 demo-activity.ts 保持一致)
const DEMO_ACTIVITY_ID = "act-pku-innovation-2025-fall";
// 通用演示 ID (用于 Mock 请求)
const UNIVERSAL_DEMO_ID = "00000000-0000-0000-0000-000000000000";

/**
 * 根据活动ID获取报名列表
 * 支持多种格式:
 * - event_xxx: 标准活动 ID
 * - ma_xxx: 商家活动 ID
 * - act-xxx: 演示活动 ID
 * - 00000000-...: 通用演示 ID
 */
export function getEnrollmentsByActivityId(
  activityId: string,
): MockEnrollment[] {
  // 演示活动或通用演示 ID，返回所有报名数据
  if (
    activityId === DEMO_ACTIVITY_ID ||
    activityId === UNIVERSAL_DEMO_ID ||
    activityId === "event_001"
  ) {
    console.log(
      `📋 [Mock] 匹配演示活动 ID: ${activityId}, 返回全部 ${mockEnrollments.length} 条报名数据`,
    );
    return mockEnrollments;
  }

  // 商家活动 ma_001 - 返回 ma_001 的报名数据
  if (activityId === "ma_001") {
    const ma001Enrollments = mockEnrollments.filter(
      (e) => e.activity_id === "ma_001",
    );
    console.log(
      `📋 [Mock] 商家活动 ID: ${activityId}, 返回 ${ma001Enrollments.length} 条报名数据`,
    );
    return ma001Enrollments;
  }

  // 商家活动 ma_002 - 返回 ma_002 的报名数据
  if (activityId === "ma_002") {
    const ma002Enrollments = mockEnrollments.filter(
      (e) => e.activity_id === "ma_002",
    );
    console.log(
      `📋 [Mock] 商家活动 ID: ${activityId}, 返回 ${ma002Enrollments.length} 条报名数据`,
    );
    return ma002Enrollments;
  }

  // 其他情况按 activity_id 精确匹配
  const filtered = mockEnrollments.filter((e) => e.activity_id === activityId);
  console.log(
    `📋 [Mock] 活动 ID: ${activityId}, 匹配到 ${filtered.length} 条报名数据`,
  );
  return filtered;
}

/**
 * 获取报名统计
 */
export function getEnrollmentStats(activityId: string) {
  const enrollments = getEnrollmentsByActivityId(activityId);
  return {
    total: enrollments.length,
    confirmed: enrollments.filter((e) => e.status === "confirmed").length,
    pending: enrollments.filter((e) => e.status === "pending").length,
    waitlist: enrollments.filter((e) => e.status === "waitlist").length,
    cancelled: enrollments.filter((e) => e.status === "cancelled").length,
  };
}
